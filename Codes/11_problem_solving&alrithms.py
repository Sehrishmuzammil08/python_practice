# Problem: Calculate the area of a rectangle
# ============================================================
# Steps:
# 1. Get length from user
# 2. Get width from user
# 3. Multiply length and width
# 4. Display area

length = float(input("Enter length: "))
width = float(input("Enter width: "))
area = length * width
print("Area =", area)

# Test Case:
# Input:  Length = 5, Width = 4
# Output: Area = 20.0
